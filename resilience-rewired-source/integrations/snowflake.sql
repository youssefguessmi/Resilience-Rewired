CREATE TABLE IF NOT EXISTS ACCOUNT_MONTHLY (
  ACCOUNT_ID NUMBER,
  MONTH DATE,
  MONEY_IN FLOAT,
  MONEY_OUT FLOAT,
  HOUSEHOLD_BILLS FLOAT,
  INSURANCE FLOAT,
  LOAN_PAYMENTS FLOAT,
  AVG_DAILY_BALANCE FLOAT
);

CREATE TABLE IF NOT EXISTS LOANS (
  LOAN_ID NUMBER,
  ACCOUNT_ID NUMBER,
  MONTHLY_PAYMENT FLOAT,
  STATUS VARCHAR(1)
);

-- Load the challenge CSVs into these tables with your Snowflake stage.
-- Median monthly values and six most recent average balances follow the challenge README.
WITH BASE AS (
  SELECT ACCOUNT_ID,
    MEDIAN(MONEY_IN) AS I,
    MEDIAN(MONEY_OUT) AS S,
    MEDIAN(HOUSEHOLD_BILLS) AS H
  FROM ACCOUNT_MONTHLY
  GROUP BY ACCOUNT_ID
), RECENT AS (
  SELECT ACCOUNT_ID, AVG(AVG_DAILY_BALANCE) AS B
  FROM (
    SELECT ACCOUNT_ID, AVG_DAILY_BALANCE,
      ROW_NUMBER() OVER (PARTITION BY ACCOUNT_ID ORDER BY MONTH DESC) AS RN
    FROM ACCOUNT_MONTHLY
  )
  WHERE RN <= 6
  GROUP BY ACCOUNT_ID
), COHORT AS (
  SELECT B.ACCOUNT_ID, B.I, B.S, R.B,
    IFF(L.STATUS IN ('C', 'D'), 1, 0) AS ACTIVE_LOAN
  FROM BASE B
  JOIN RECENT R ON R.ACCOUNT_ID = B.ACCOUNT_ID
  LEFT JOIN LOANS L ON L.ACCOUNT_ID = B.ACCOUNT_ID
), SCENARIOS AS (
  SELECT ACTIVE_LOAN,
    IFF(B <= 0, 0,
      IFF(S <= 0.55 * I, 120,
        LEAST(B / NULLIF(S - 0.55 * I, 0), 120))) AS RUNWAY
  FROM COHORT
)
SELECT ACTIVE_LOAN, COUNT(*) AS ACCOUNTS,
  SUM(IFF(RUNWAY < 6, 1, 0)) AS UNDER_SIX_MONTHS,
  ROUND(100.0 * SUM(IFF(RUNWAY < 6, 1, 0)) / COUNT(*), 1) AS PCT_UNDER_SIX_MONTHS
FROM SCENARIOS
GROUP BY ACTIVE_LOAN
ORDER BY ACTIVE_LOAN DESC;
